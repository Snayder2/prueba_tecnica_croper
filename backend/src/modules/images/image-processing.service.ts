import { BadRequestException, Injectable, UnsupportedMediaTypeException } from '@nestjs/common';
import sharp from 'sharp';

/** Larger inputs are rejected before decoding them ("decompression bombs"). */
export const MAX_INPUT_PIXELS = 40_000_000;
export const LARGE_IMAGE_MAX_SIDE = 1200;
export const THUMBNAIL_SIDE = 400;

export interface ProcessedImage {
  /** WebP, at most 1200 × 1200 px, never enlarged. */
  large: Buffer;
  /** WebP, 400 × 400 px, centered crop. */
  thumbnail: Buffer;
  /** Size of the large image. */
  width: number;
  height: number;
}

/**
 * Re-encodes every uploaded image (spec 03 §7.3): what is stored and served is
 * always a WebP generated by the server, never the user's file. Re-encoding
 * drops all metadata (GPS location, camera, etc.), because sharp only keeps it
 * when asked to with withMetadata()/keepMetadata().
 */
@Injectable()
export class ImageProcessingService {
  async process(input: Buffer): Promise<ProcessedImage> {
    try {
      // rotate() applies the EXIF orientation before the metadata is dropped.
      const source = sharp(input, { limitInputPixels: MAX_INPUT_PIXELS }).rotate();

      const [large, thumbnail] = await Promise.all([
        source
          .clone()
          .resize(LARGE_IMAGE_MAX_SIDE, LARGE_IMAGE_MAX_SIDE, {
            fit: 'inside',
            withoutEnlargement: true,
          })
          .webp({ quality: 80 })
          .toBuffer({ resolveWithObject: true }),
        source
          .clone()
          .resize(THUMBNAIL_SIDE, THUMBNAIL_SIDE, { fit: 'cover', position: 'centre' })
          .webp({ quality: 75 })
          .toBuffer(),
      ]);

      return {
        large: large.data,
        thumbnail,
        width: large.info.width,
        height: large.info.height,
      };
    } catch (error) {
      throw this.translateError(error);
    }
  }

  private translateError(error: unknown): Error {
    const message = error instanceof Error ? error.message : '';
    if (/pixel limit/i.test(message)) {
      return new BadRequestException('Image dimensions too large');
    }
    // Passed the magic-number check but cannot be decoded: not a valid image.
    return new UnsupportedMediaTypeException('Unsupported file type');
  }
}
